import AppKit

/// 监听系统剪贴板：用户在任何 App 里拷贝了文件或图片，就自动挂到绳上。
///
/// 只用 changeCount 和 types 判断有没有新内容，这两项不会触发系统的剪贴板访问提示；
/// 只有类型里出现文件或图片时才读取内容，复制文字不会打扰用户。
@MainActor
final class ClipboardWatcher {
    enum Content {
        case files([URL])
        case image(ImageClip, sourceURL: URL?)
    }

    var onContent: ((Content) -> Void)?

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var lastImage: ImageClip?
    private var timer: Timer?

    /// 密码管理器等标记为隐私、临时的内容一律跳过（nspasteboard.org 约定）
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
    ]

    init() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        // 启动前就在剪贴板里的内容不挂
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        guard let content = Self.content(of: pasteboard) else { return }
        if case .image(let clip, _) = content {
            // 同一张图连续拷贝两次只挂一次
            guard clip != lastImage else { return }
            lastImage = clip
        }
        onContent?(content)
    }

    static func content(of pasteboard: NSPasteboard) -> Content? {
        let types = Set(pasteboard.types ?? [])
        guard !types.isEmpty, types.isDisjoint(with: skippedTypes) else { return nil }

        // Finder 拷贝文件时也会附带图标图片，所以先看文件
        if types.contains(.fileURL) {
            let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
            return urls.isEmpty ? nil : .files(urls)
        }

        if let (clip, source) = ImageClip.read(from: pasteboard) {
            return .image(clip, sourceURL: source)
        }
        return nil
    }
}
